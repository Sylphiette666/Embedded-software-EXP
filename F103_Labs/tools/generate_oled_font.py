"""Generate the small teaching-display bitmap subset; Pillow is only needed here.

Run on Windows with bundled Python/Pillow. The checked-in header is sufficient
for Keil; building firmware never requires Python or installed desktop fonts.
Each glyph is column bytes in SSD1306 page order (bit 0 is the upper pixel).
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'Labs/08_Application/oled_font.h'
OUT = ROOT / 'Build/oled_font_preview.png'
MESSAGE = '嵌入式实验完成啦'

def glyph(char, width, font):
    im = Image.new('1', (width, 16), 0)
    draw = ImageDraw.Draw(im)
    left, top, right, bottom = draw.textbbox((0, 0), char, font=font)
    # Keep ASCII on one baseline; center all CJK ideographs as full 16px cells.
    y = 0 if width == 8 else (16 - (bottom-top)) // 2 - top
    draw.text(((width-(right-left))//2-left, y), char, font=font, fill=1)
    return [sum(int(bool(im.getpixel((x, p*8+b)))) << b for b in range(8))
            for p in range(2) for x in range(width)]

def draw_bytes(image, x0, y0, data, width):
    for p in range(2):
        for x in range(width):
            for b in range(8):
                image.putpixel((x0+x, y0+p*8+b), 255 if data[p*width+x] & (1<<b) else 0)

def main():
    ascii_font = ImageFont.truetype('C:/Windows/Fonts/consola.ttf', 13)
    cjk_font = ImageFont.truetype('C:/Windows/Fonts/simsun.ttc', 16)
    ascii_glyphs = [glyph(chr(c), 8, ascii_font) for c in range(32, 127)]
    cjk_glyphs = [glyph(c, 16, cjk_font) for c in MESSAGE]
    text = ['/* Generated by tools/generate_oled_font.py. Column/page bitmaps. */',
            '#ifndef LAB8_OLED_FONT_H', '#define LAB8_OLED_FONT_H', '#include <stdint.h>',
            'static const uint8_t oled_font_ascii[95][16] = {']
    for c, data in zip(range(32, 127), ascii_glyphs):
        text.append('    {' + ','.join(f'0x{b:02X}' for b in data) + f'}}, /* ASCII {c} */')
    text += ['};', '/* In order: U+5D4C U+5165 U+5F0F U+5B9E U+9A8C U+5B8C U+6210 U+5566 */',
             'static const uint8_t oled_font_completed[8][32] = {']
    for data in cjk_glyphs:
        text.append('    {' + ','.join(f'0x{b:02X}' for b in data) + '},')
    text += ['};', '#endif', '']
    DEST.write_text('\n'.join(text), encoding='ascii')
    im = Image.new('L', (128, 64), 0)
    for y, line in ((0,'LAB8 OLED READY'),(16,'BLINK: ON'),(48,'K1:BLINK K4:MSG')):
        for x, char in enumerate(line):
            draw_bytes(im, x*8, y, ascii_glyphs[ord(char)-32], 8)
    for x, data in enumerate(cjk_glyphs):
        draw_bytes(im, x*16, 32, data, 16)
    OUT.parent.mkdir(exist_ok=True)
    im.resize((1024, 512), Image.Resampling.NEAREST).save(OUT)
    print(DEST)
    print(OUT)

if __name__ == '__main__':
    main()
